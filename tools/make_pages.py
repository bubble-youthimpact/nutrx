#!/usr/bin/env python3
"""
Nutrx page generator
--------------------
Rebuilds every page folder (team/, privacy/, series/health-fraud-files/ …), 404.html,
sitemap.xml, robots.txt, CNAME and assets/js/site.js from two files:

  site.json   – web address, page titles and descriptions
  index.html  – the site itself (edit page text here)

Run it from the repository folder after changing either file:
    python3 tools/make_pages.py
"""
import json, os, re, html, sys
from urllib.parse import urlparse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def p(*a): return os.path.join(ROOT, *a)

site = json.load(open(p('site.json'), encoding='utf-8'))
domain = (site.get('domain') or '').rstrip('/')
base = site.get('base') or '/'
if not base.startswith('/'): base = '/' + base
if not base.endswith('/'): base += '/'
pages = site['pages']
og_image = site.get('ogImage', 'assets/img/og-image.jpg')
master = open(p('index.html'), encoding='utf-8').read()
if '<!-- page-head:start -->' not in master:
    sys.exit('index.html is missing the <!-- page-head:start --> marker')

def url_for(key):
    return (domain + base + (key + '/' if key else '')) if domain else ''

def head(key, prefix):
    m = pages[key]
    t, d = html.escape(m['title']), html.escape(m['description'])
    noindex = m.get('noindex', False)
    out = [f'<title>{t}</title>',
           f'<meta name="description" content="{d}" />',
           f'<meta name="robots" content="{"noindex" if noindex else "index,follow"}" />',
           '<meta name="theme-color" content="#154959" />']
    if domain and not noindex and key != '404':
        out.append(f'<link rel="canonical" href="{url_for(key)}" />')
    out += [f'<link rel="icon" href="{prefix}assets/icons/favicon.ico" sizes="any" data-asset="assets/icons/favicon.ico" />',
            f'<link rel="icon" type="image/png" sizes="32x32" href="{prefix}assets/icons/favicon-32.png" data-asset="assets/icons/favicon-32.png" />',
            f'<link rel="apple-touch-icon" href="{prefix}assets/icons/apple-touch-icon.png" data-asset="assets/icons/apple-touch-icon.png" />',
            f'<link rel="manifest" href="{prefix}site.webmanifest" data-asset="site.webmanifest" />',
            f'<meta property="og:type" content="website" />',
            f'<meta property="og:site_name" content="{html.escape(site.get("name","Nutrx"))}" />',
            f'<meta property="og:title" content="{t}" />',
            f'<meta property="og:description" content="{d}" />',
            '<meta property="og:locale" content="en_US" />',
            '<meta name="twitter:card" content="summary_large_image" />',
            f'<meta name="twitter:title" content="{t}" />',
            f'<meta name="twitter:description" content="{d}" />']
    if domain:
        img = domain + base + og_image
        out += [f'<meta property="og:url" content="{url_for(key) if key != "404" else domain + base}" />',
                f'<meta property="og:image" content="{img}" />',
                '<meta property="og:image:width" content="1200" />', '<meta property="og:image:height" content="630" />',
                f'<meta property="og:image:alt" content="{html.escape(site.get("ogImageAlt","Nutrx homepage"))}" />',
                f'<meta name="twitter:image" content="{img}" />']
    return '<!-- page-head:start -->\n' + '\n'.join(out) + '\n<!-- page-head:end -->'

def render(key, prefix):
    doc = re.sub(r'<!-- page-head:start -->.*?<!-- page-head:end -->', lambda _: head(key, prefix), master, count=1, flags=re.S)
    # static references to our own files: make them correct for this folder depth
    doc = re.sub(r'((?:src|href)=")(?:\.\./)*(assets/|site\.webmanifest)', lambda m: m.group(1) + prefix + m.group(2), doc)
    doc = re.sub(r'((?:src|href)=")/(assets/|site\.webmanifest)', lambda m: m.group(1) + prefix + m.group(2), doc)
    return doc

written = []
# 1) site.js – settings the app reads at runtime
os.makedirs(p('assets', 'js'), exist_ok=True)
with open(p('assets', 'js', 'site.js'), 'w', encoding='utf-8') as f:
    f.write('/* Generated by tools/make_pages.py from site.json — edit site.json, not this file. */\n')
    f.write('window.NUTRX_SITE = ' + json.dumps({'base': base, 'domain': domain, 'pages': pages}, ensure_ascii=False, indent=1) + ';\n')
written.append('assets/js/site.js')

# 2) every page
for key in pages:
    if key == '404': continue
    depth = key.count('/') + 1 if key else 0
    prefix = '../' * depth
    out = p(key, 'index.html') if key else p('index.html')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', encoding='utf-8').write(render(key, prefix))
    written.append(os.path.relpath(out, ROOT))
# 404 can be shown at any address, so it uses root-based paths
open(p('404.html'), 'w', encoding='utf-8').write(render('404', base))
written.append('404.html')

# 3) sitemap, robots, CNAME
if domain:
    urls = [url_for(k) for k, m in pages.items() if k != '404' and not m.get('noindex')]
    sm = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + \
         ''.join(f'  <url><loc>{html.escape(u)}</loc></url>\n' for u in urls) + '</urlset>\n'
    open(p('sitemap.xml'), 'w', encoding='utf-8').write(sm); written.append('sitemap.xml')
robots = 'User-agent: *\nAllow: /\nDisallow: ' + base + 'profile/\n' + (f'\nSitemap: {domain}{base}sitemap.xml\n' if domain else '')
open(p('robots.txt'), 'w', encoding='utf-8').write(robots); written.append('robots.txt')
host = urlparse(domain).netloc if domain else ''
if host and not host.endswith('github.io'):
    open(p('CNAME'), 'w').write(host + '\n'); written.append('CNAME')
elif os.path.exists(p('CNAME')):
    os.remove(p('CNAME'))

print('Updated', len(written), 'files:'); [print('  ' + w) for w in written]
if not domain: print('\nNote: "domain" in site.json is empty, so link previews have no image and there is no sitemap yet.')
